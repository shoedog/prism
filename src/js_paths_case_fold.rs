#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn simple_fold_equivalence_and_no_full_expansion() {
        for (a, b) in [
            ('Σ', 'ς'),
            ('K', 'K'),
            ('S', 'ſ'),
            ('ß', 'ẞ'),
            ('μ', 'µ'),
            ('Ꭰ', 'ꭰ'),
            ('ΐ', 'ΐ'),
            ('ΰ', 'ΰ'),
            ('ﬅ', 'ﬆ'),
        ] {
            assert_eq!(simple(a), simple(b));
        }
        assert_eq!(simple('İ'), 'İ');
        assert_eq!(simple('ß'), 'ß');
    }
}
