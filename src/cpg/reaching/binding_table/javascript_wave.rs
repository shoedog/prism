#[allow(clippy::too_many_arguments)]
const fn row(
    kind: &'static str,
    variant: Option<Predicate>,
    roles: RoleSet,
    fields: &'static [&'static str],
    declaration: Option<DeclarationKind>,
    visibility: Visibility,
    ruling: Ruling,
    regression: &'static str,
) -> BindingRow {
    BindingRow {
        language: Language::JavaScript,
        kind,
        variant,
        roles,
        fields,
        declaration,
        visibility,
        ruling,
        regression,
    }
}

